import {readFile,writeFile,mkdir} from 'node:fs/promises';
import vm from 'node:vm';
const context = vm.createContext({window:{}});
for (const filename of ['questions.js','questions-more.js']) vm.runInContext(await readFile(new URL('../js/'+filename,import.meta.url),'utf8'),context,{timeout:5000});
const questions=context.window.ORT_QUESTIONS;
if (!Array.isArray(questions) || new Set(questions.map(q=>q.id)).size!==questions.length) throw new Error('Invalid question bank');
await mkdir(new URL('../server/',import.meta.url),{recursive:true});
await writeFile(new URL('../server/question-bank.mjs',import.meta.url),'// Generated by scripts/build-question-bank.mjs. Served only by the protected API.\nexport const questions = '+JSON.stringify(questions)+';\n');
console.log('Built server question bank: '+questions.length+' original questions.');
